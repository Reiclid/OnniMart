const HOME_OTHER: CategorySlug[] = ['household', 'other'];
const CARE: CategorySlug[] = ['beauty'];
const PETS: CategorySlug[] = ['pets'];
const KIDS: CategorySlug[] = ['baby'];

/** Слово(а) між головним словом і "для": "Засіб універсальний Auchan для чищення" */
/** Лише на початку назви чи після розділювача: "Vitamin B12", але не "Körpercreme, Vitamin E" */
const START = '(?<![\\p{L}\\d,]\\s)';

const GAP = '(?:\\S+\\s+){0,3}';

/** fold() замінює й → и, ї → і; регулярний вираз складати з fold не можна (\p, \S) */
const folded = (pattern: string) => pattern.replace(/й/g, 'и').replace(/ї/g, 'і');

const def = (slug: string, parent: string | undefined, categories: CategorySlug[], names: [string[], string[], string[]], stems?: string[], phrases?: string[]): Concept => ({
  slug,
  parent,
  categories,
  names: { uk: names[0], de: names[1], en: names[2] },
  // Основи порівнюються зі згорнутою назвою (й → и, ї → і): згортаємо й їх
  stems: stems?.map(folded),
  phrases: phrases?.map(folded),
});

