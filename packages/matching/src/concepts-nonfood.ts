import type { CategorySlug } from './categories';
import type { Concept } from './concepts';

/**
 * Непродуктові поняття (PRD-19): побутова хімія, краса, тварини, діти. Правила ті самі, що й
 * у concepts.ts. Додатково `phrases` — вирази, які дивляться на всю назву, а не на частину до
 * прийменника: "Засіб для прання", "Корм сухий … для котів" — головне слово ("засіб", "корм")
 * ще нічого не каже, а вирішує те, що після "для".
 */
